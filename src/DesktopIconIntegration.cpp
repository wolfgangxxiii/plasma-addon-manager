#include "DesktopIconIntegration.h"

#include <QDir>
#include <QFile>
#include <QFileInfo>
#include <QSaveFile>

namespace DesktopIconIntegration {
namespace {

constexpr auto generatedMarker = "X-PlasmaAddonManager-AutoGenerated=true";

bool writeIfChanged(const QString &path, const QByteArray &data, QString *error) {
    QFile current(path);
    if (current.open(QIODevice::ReadOnly) && current.readAll() == data) {
        return true;
    }
    if (!QDir().mkpath(QFileInfo(path).absolutePath())) {
        if (error) *error = QStringLiteral("Cannot create directory for %1").arg(path);
        return false;
    }
    QSaveFile output(path);
    if (!output.open(QIODevice::WriteOnly) || output.write(data) != data.size()
            || !output.commit()) {
        if (error) *error = QStringLiteral("Cannot save %1: %2").arg(path, output.errorString());
        return false;
    }
    return true;
}

QString escapedExecPath(QString path) {
    // .desktop quoted-string escaping and doubled freedesktop field-code '%'.
    path.replace(QLatin1Char('\\'), QStringLiteral("\\\\\\\\"));
    path.replace(QLatin1Char('"'), QStringLiteral("\\\\\""));
    path.replace(QLatin1Char('$'), QStringLiteral("\\\\$"));
    path.replace(QLatin1Char('`'), QStringLiteral("\\\\`"));
    path.replace(QLatin1Char('%'), QStringLiteral("%%"));
    return QStringLiteral("\"") + path + QStringLiteral("\"");
}

} // namespace

QString desktopId() {
    return QStringLiteral("io.github.wolfgangxxiii.PlasmaAddonManager");
}

bool ensureAppImageIcon(const QString &appImagePath, const QString &dataHome,
                        const QStringList &systemDataLocations, QString *error) {
    const QString appImage = QFileInfo(appImagePath).absoluteFilePath();
    if (appImagePath.isEmpty() || dataHome.isEmpty()
            || appImage.contains(QLatin1Char('\n')) || appImage.contains(QLatin1Char('\r'))) {
        if (error) *error = QStringLiteral("Invalid AppImage or XDG data location");
        return false;
    }

    const QString desktopName = desktopId() + QStringLiteral(".desktop");
    const QString desktopPath = QDir(dataHome).filePath(QStringLiteral("applications/") + desktopName);

    // A system-installed entry already supplies the correct identity. Do not
    // shadow it with a hidden user entry, or override a user's own launcher.
    for (const QString &location : systemDataLocations) {
        if (QDir(location).absolutePath() != QDir(dataHome).absolutePath()
                && QFileInfo::exists(QDir(location).filePath(QStringLiteral("applications/") + desktopName))) {
            return true;
        }
    }
    QFile installedDesktop(desktopPath);
    if (installedDesktop.exists()) {
        if (!installedDesktop.open(QIODevice::ReadOnly)) {
            if (error) *error = QStringLiteral("Cannot inspect existing desktop entry");
            return false;
        }
        if (!installedDesktop.readAll().contains(generatedMarker)) {
            return true; // Preserve user-managed desktop entries.
        }
    }

    QFile bundledIcon(QStringLiteral(":/images/app.png"));
    if (!bundledIcon.open(QIODevice::ReadOnly)) {
        if (error) *error = QStringLiteral("Bundled application icon is missing");
        return false;
    }
    const QByteArray iconBytes = bundledIcon.readAll();
    if (!iconBytes.startsWith(QByteArray::fromHex("89504e470d0a1a0a"))) {
        if (error) *error = QStringLiteral("Bundled application icon is not PNG");
        return false;
    }
    const QString iconPath = QDir(dataHome).filePath(
        QStringLiteral("icons/hicolor/256x256/apps/") + desktopId() + QStringLiteral(".png"));
    if (!writeIfChanged(iconPath, iconBytes, error)) return false;

    // NoDisplay avoids a duplicate launcher if an AppImage manager installed
    // its own .desktop file. KWin can still use this entry for window icons.
    const QString desktop = QStringLiteral(
        "[Desktop Entry]\n"
        "Type=Application\n"
        "Name=Plasma Addon Manager\n"
        "Name[pl]=Menedżer dodatków Plasma\n"
        "Comment=Manage KDE Plasma add-ons\n"
        "Exec=%1\n"
        "Icon=%2\n"
        "Terminal=false\n"
        "NoDisplay=true\n"
        "StartupNotify=true\n"
        "StartupWMClass=plasma-addon-manager\n"
        "X-PlasmaAddonManager-AutoGenerated=true\n")
        .arg(escapedExecPath(appImage), iconPath);
    return writeIfChanged(desktopPath, desktop.toUtf8(), error);
}

} // namespace DesktopIconIntegration
