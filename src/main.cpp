// Test the desktop identity and icon registration without touching the host's
// XDG directories. The real AppImage registers this before showing a window.
static int desktopIconTest() {
    QTemporaryDir directory;
    if (!directory.isValid()) return 6;
    const QString dataHome = directory.filePath(QStringLiteral("xdg data"));
    const QString imagePath = directory.filePath(QStringLiteral("My AppImage 100%.AppImage"));
    QString error;
    if (!DesktopIconIntegration::ensureAppImageIcon(imagePath, dataHome, {}, &error)) {
        qCritical() << "Desktop icon test failed:" << error;
        return 6;
    }
    const QString id = DesktopIconIntegration::desktopId();
    QFile desktop(QDir(dataHome).filePath(QStringLiteral("applications/") + id + QStringLiteral(".desktop")));
    QFile installedIcon(QDir(dataHome).filePath(QStringLiteral("icons/hicolor/256x256/apps/")
                                            + id + QStringLiteral(".png")));
    QFile bundledIcon(QStringLiteral(":/images/app.png"));
    if (!desktop.open(QIODevice::ReadOnly) || !installedIcon.open(QIODevice::ReadOnly)
            || !bundledIcon.open(QIODevice::ReadOnly)) return 6;
    const QByteArray content = desktop.readAll();
    if (!content.contains("NoDisplay=true")
            || !content.contains("X-PlasmaAddonManager-AutoGenerated=true")
            || !content.contains("My AppImage 100%%.AppImage")
            || !content.contains(id.toUtf8() + QByteArrayLiteral(".png"))
            || installedIcon.readAll() != bundledIcon.readAll()) {
        qCritical() << "Desktop integration identity, icon or Exec mismatch";
        return 6;
    }
    qInfo() << "Wayland desktop icon integration test passed";
    return 0;
}

// Exercise the real asynchronous bridge with a local fake helper. No system
// settings or KDE add-ons are touched: this is a pure session-log regression test.
static int sessionLogTest() {
    QTemporaryDir directory;
    if (!directory.isValid()) {
        qCritical() << "Cannot create session log test directory";
        return 4;
    }
    const QString helperPath = directory.filePath(QStringLiteral("fake-plasma-addon-helper"));
    QFile helper(helperPath);
    const QByteArray script =
        "#!/bin/sh\n"
        "case \"$1\" in\n"
        "  diagnose) printf 'diagnostic output\\n' ;;\n"
        "  check) printf 'network unavailable\\n' >&2; exit 23 ;;\n"
        "  timer) printf 'timer output\\n' ;;\n"
        "  *) exit 42 ;;\n"
        "esac\n";
    if (!helper.open(QIODevice::WriteOnly) || helper.write(script) != script.size()) {
        qCritical() << "Cannot create fake helper";
        return 4;
    }
    helper.close();
    if (!helper.setPermissions(QFileDevice::ReadUser | QFileDevice::WriteUser
                               | QFileDevice::ExeUser)) {
        qCritical() << "Cannot make fake helper executable";
        return 4;
    }
    qputenv("PLASMA_ADDON_HELPER", QFile::encodeName(helperPath));
    BackendBridge backend;
    const auto run = [&backend](const QString &action) {
        QEventLoop loop;
        QTimer timeout;
        timeout.setSingleShot(true);
        bool timedOut = false;
        QObject::connect(&timeout, &QTimer::timeout, &loop, [&] {
            timedOut = true;
            loop.quit();
        });
        QObject::connect(&backend, &BackendBridge::runningChanged, &loop, [&] {
            if (!backend.running()) {
                loop.quit();
            }
        });
        backend.runAction(action);
        if (backend.running()) {
            timeout.start(10000);
            loop.exec();
        }
        return !timedOut && !backend.running();
    };
    if (!run(QStringLiteral("diagnose")) || !backend.lastOperationSucceeded()
            || backend.progressDetail() != QStringLiteral("diagnostic output")
            || !run(QStringLiteral("check")) || backend.lastOperationSucceeded()
            || backend.progressDetail() != QStringLiteral("network unavailable")
            || !backend.lastOperationError().contains(QStringLiteral("network unavailable"))
            || !run(QStringLiteral("timer")) || !backend.lastOperationSucceeded()
            || backend.progressDetail() != QStringLiteral("timer output")) {
        qCritical() << "Session log test: status or live progress did not follow the action";
        return 4;
    }
    const QString log = backend.output();
    const int first = log.indexOf(QStringLiteral("▶ diagnose"));
    const int second = log.indexOf(QStringLiteral("▶ check"));
    const int third = log.indexOf(QStringLiteral("▶ timer"));
    if (first < 0 || second <= first || third <= second
            || !log.contains(QStringLiteral("diagnostic output"))
            || !log.contains(QStringLiteral("network unavailable"))
            || !log.contains(QStringLiteral("timer output"))
            || !log.contains(QStringLiteral("✓ diagnose"))
            || !log.contains(QStringLiteral("✗ check"))
            || !log.contains(QStringLiteral("✓ timer"))) {
        qCritical() << "Session log test: earlier actions or their output went missing" << log;
        return 4;
    }
    qInfo() << "Session log test passed: successful and failed actions are preserved";
    return 0;
}

int main(int argc, char *argv[]) {
    // AppImages combine bundled Qt with graphics drivers from the host. On
    // Bazzite (including NVIDIA laptops), the software Qt Quick renderer
    // avoids the fatal QRhi OpenGL context failure seen in the first preview.
    // Users may explicitly override QT_QUICK_BACKEND to opt into GPU rendering.
    if (!qEnvironmentVariableIsEmpty("APPIMAGE") && qEnvironmentVariableIsEmpty("QT_QUICK_BACKEND")) {
        qputenv("QT_QUICK_BACKEND", "software");
    }
    QGuiApplication app(argc, argv);
    // Qt supplies the icon to X11 and compatible Wayland protocols. Older
    // Wayland compositors also need a matching host-visible .desktop entry.
    const QIcon appIcon(QStringLiteral(":/images/app.png"));
    if (appIcon.isNull()) {
        qCritical() << "Application icon resource is missing";
        return 5;
    }
    QGuiApplication::setWindowIcon(appIcon);
    QCoreApplication::setOrganizationName(QStringLiteral("wolfgangxxiii"));
    QCoreApplication::setApplicationName(QStringLiteral("Plasma Addon Manager"));
    QGuiApplication::setDesktopFileName(DesktopIconIntegration::desktopId());
    // Make plugins bundled outside Qt's system prefix visible to Kirigami's
    // platform factory, which also loads plugins under kf6/kirigami/platform.
    const QDir appDirectory(QCoreApplication::applicationDirPath());
    const QString appPlugins = QDir::cleanPath(appDirectory.filePath(QStringLiteral("../plugins")));
    if (QDir(appPlugins).exists()) {
        QCoreApplication::addLibraryPath(appPlugins);
    }
    if (qEnvironmentVariableIsEmpty("QT_QUICK_CONTROLS_STYLE")) {
        QQuickStyle::setStyle(QStringLiteral("org.kde.desktop"));
    }

    const bool smokeTest = QCoreApplication::arguments().contains(QStringLiteral("--self-test"));
    if (QCoreApplication::arguments().contains(QStringLiteral("--self-test-desktop-icon"))) {
        return desktopIconTest();
    }
    if (QCoreApplication::arguments().contains(QStringLiteral("--self-test-session-log"))) {
        return sessionLogTest();
    }
    if (!smokeTest && !qEnvironmentVariableIsEmpty("APPIMAGE")
            && QGuiApplication::platformName().startsWith(QStringLiteral("wayland"))) {
        QString error;
        if (!DesktopIconIntegration::ensureAppImageIcon(
                    qEnvironmentVariable("APPIMAGE"),
                    QStandardPaths::writableLocation(QStandardPaths::GenericDataLocation),
                    QStandardPaths::standardLocations(QStandardPaths::GenericDataLocation), &error)) {
            qWarning() << "Could not register the AppImage's KDE/Wayland icon:" << error;
        }
    }
    const QString bundledKirigami = QDir(appPlugins).filePath(
        QStringLiteral("kf6/kirigami/platform/org.kde.desktop.so"));
    if (smokeTest && QFileInfo::exists(bundledKirigami)) {
        QPluginLoader loader(bundledKirigami);
        if (!loader.load()) {
            qCritical() << "Bundled Kirigami KDE platform plugin cannot load:" << loader.errorString();
            return 2;
        }
        qInfo() << "Kirigami KDE platform plugin verified:" << bundledKirigami;
    }

    BackendBridge backend;
    QQmlApplicationEngine engine;
    bool qmlBindingError = false;
    if (smokeTest) {
        QObject::connect(&engine, &QQmlEngine::warnings, &app,
                         [&qmlBindingError](const QList<QQmlError> &warnings) {
            for (const QQmlError &warning : warnings) {
                const QString message = warning.toString();
                if (message.contains(QStringLiteral("ReferenceError"))
                        || message.contains(QStringLiteral("TypeError"))) {
                    qCritical() << "QML smoke test binding error:" << message;
                    qmlBindingError = true;
                }
            }
        });
    }
    engine.rootContext()->setContextProperty(QStringLiteral("backend"), &backend);
    engine.load(QUrl(QStringLiteral("qrc:/qml/Main.qml")));
    if (engine.rootObjects().isEmpty()) {
        return 1;
    }
    // Set the icon on the actual top-level QWindow too. Older Wayland
    // sessions resolve the matching desktop file registered above instead.
    auto *mainWindow = qobject_cast<QWindow *>(engine.rootObjects().first());
    if (!mainWindow) {
        qCritical() << "The Kirigami root object is not a window";
        return 5;
    }
    mainWindow->setIcon(appIcon);
    if (smokeTest &&
            (mainWindow->icon().isNull() ||
             QGuiApplication::desktopFileName() != DesktopIconIntegration::desktopId())) {
        qCritical() << "Application icon or desktop identity smoke test failed";
        return 5;
    }
    // Package smoke tests verify that all QML imports and the window load.
    // No host state is changed, and the diagnostic helper is not started.
    if (smokeTest) {
        // Create the repeated add-on cards too; merely loading the initial
        // empty window never instantiates their QML delegates.
        QObject *root = engine.rootObjects().first();
        backend.dashboardLoaded(QStringLiteral(
            "{\"distribution\":\"openSUSE Tumbleweed\",\"updater_version\":\"0.2.1\",\"bsdtar_available\":false}"));
        backend.inventoryLoaded(QStringLiteral(
            "{\"addons\":[{\"name\":\"Test Widget\",\"directory_name\":\"test\","
            "\"version\":\"1.0\",\"component_type\":\"Plasma Widget\",\"is_system\":false}],"
            "\"system_warning\":\"System inventory omitted\"}"));
        QCoreApplication::processEvents();
        if (!root->property("bsdtarMissing").toBool()
                || !root->property("inventoryReady").toBool()
                || root->property("inventoryWarning").toString().isEmpty()) {
            qCritical() << "QML smoke test: openSUSE diagnostics or inventory contract failed";
            return 3;
        }
        QVariantMap addon;
        addon.insert(QStringLiteral("name"), QStringLiteral("Test Plasma Widget"));
        addon.insert(QStringLiteral("directory_name"), QStringLiteral("test-widget"));
        addon.insert(QStringLiteral("version"), QStringLiteral("1.0"));
        addon.insert(QStringLiteral("component_type"), QStringLiteral("Plasma Widget"));
        addon.insert(QStringLiteral("is_system"), false);
        QVariantMap update;
        update.insert(QStringLiteral("installed"), addon);
        update.insert(QStringLiteral("latest_version"), QStringLiteral("1.1"));
        root->setProperty("installedAddons", QVariantList{addon});
        root->setProperty("inventoryReady", true);
        root->setProperty("section", 1);
        QCoreApplication::processEvents();
        root->setProperty("availableUpdates", QVariantList{update});
        root->setProperty("updatesReady", true);
        root->setProperty("addonView", 1);
        QCoreApplication::processEvents();
        root->setProperty("section", 2);
        QCoreApplication::processEvents();
        root->setProperty("section", 3);
        QCoreApplication::processEvents();
        root->setProperty("section", 4);
        QCoreApplication::processEvents();
        QObject *aboutLogo = root->findChild<QObject *>(QStringLiteral("aboutBrandIcon"));
        QObject *topNavigation = root->findChild<QObject *>(QStringLiteral("horizontalNavigation"));
        QObject *languageSelector = root->findChild<QObject *>(QStringLiteral("interfaceLanguageSelector"));
        QObject *mainScroll = root->findChild<QObject *>(QStringLiteral("mainContentScroll"));
        QObject *sidebar = root->findChild<QObject *>(QStringLiteral("notificationSidebar"));
        QObject *statusSeparator = root->findChild<QObject *>(QStringLiteral("statusSeparator"));
        if (!aboutLogo || aboutLogo->property("status").toInt() != 1
                || !topNavigation || !languageSelector || !mainScroll || !sidebar || !statusSeparator) {
            qCritical() << "QML smoke test: About icon, navigation, sidebar, status line or language control is missing";
            return 3;
        }
        const double referenceSidebarWidth = sidebar->property("width").toDouble();
        const double referenceContentWidth = mainScroll->property("width").toDouble();
        double referenceTileWidth = -1;
        for (const char *name : {"navDashboard", "navAddons", "navAutomation", "navJournal", "navAbout"}) {
            QObject *tile = root->findChild<QObject *>(QString::fromLatin1(name));
            QObject *label = tile ? tile->findChild<QObject *>(QStringLiteral("navigationLabel")) : nullptr;
            QObject *icon = tile ? tile->findChild<QObject *>(QStringLiteral("navigationImage")) : nullptr;
            if (!tile || tile->property("imageSource").toUrl().isEmpty()
                    || !icon || icon->property("status").toInt() != 1
                    || !label || label->property("text").toString().trimmed().isEmpty()) {
                qCritical() << "QML smoke test: navigation tile icon was not loaded or label is missing" << name;
                return 3;
            }
            const double tileWidth = tile->property("width").toDouble();
            if (referenceTileWidth < 0) referenceTileWidth = tileWidth;
            if (tileWidth < 70 || qAbs(tileWidth - referenceTileWidth) > 0.5) {
                qCritical() << "QML smoke test: navigation tile widths are not uniform" << name << tileWidth;
                return 3;
            }
        }
        if (referenceSidebarWidth < 280 || referenceContentWidth < 500) {
            qCritical() << "QML smoke test: desktop main/sidebar geometry is invalid"
                        << referenceContentWidth << referenceSidebarWidth;
            return 3;
        }
        root->setProperty("section", 1);
        QCoreApplication::processEvents();
        double referenceActionWidth = -1;
        for (const char *name : {"actionInstalled", "actionUpdates", "actionPreview", "actionApply"}) {
            QObject *button = root->findChild<QObject *>(QString::fromLatin1(name));
            const double width = button ? button->property("width").toDouble() : 0;
            if (referenceActionWidth < 0) referenceActionWidth = width;
            if (width < 100 || qAbs(width - referenceActionWidth) > 0.5) {
                qCritical() << "QML smoke test: add-on action buttons are not aligned" << name << width;
                return 3;
            }
        }
        root->setProperty("section", 4);
        QCoreApplication::processEvents();
        if (qAbs(sidebar->property("width").toDouble() - referenceSidebarWidth) > 0.5
                || qAbs(mainScroll->property("width").toDouble() - referenceContentWidth) > 0.5) {
            qCritical() << "QML smoke test: sidebar or content width changed between pages";
            return 3;
        }
        root->setProperty("section", 0);
        QCoreApplication::processEvents();
        if (qmlBindingError) {
            return 3;
        }
        QTimer::singleShot(0, &app, &QCoreApplication::quit);
        return app.exec();
    }
    QTimer::singleShot(0, &backend, [&backend] { backend.runAction(QStringLiteral("settings-show")); });
    return app.exec();
}
