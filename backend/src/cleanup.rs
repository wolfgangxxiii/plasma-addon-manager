//! Explicit, user-scoped removal of resources created by Plasma Addon Manager.
//!
//! This module deliberately does not uninstall shared distribution packages,
//! delete user KDE add-ons, or erase migration backups. Older installations
//! did not record ownership of external tools, so those are opt-in only.

use crate::{automation, valid_updater_version};
use anyhow::{bail, Context, Result};
use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

const MANAGED_UNIT_MARKER: &str = "# Managed by Plasma Addon Manager 0.3+";
const DESKTOP_MARKER: &str = "X-PlasmaAddonManager-AutoGenerated=true";
const APP_ID: &str = "io.github.wolfgangxxiii.PlasmaAddonManager";

#[derive(Debug, Clone, Serialize)]
pub struct CleanupItem {
    pub path: String,
    pub label_pl: String,
    pub label_en: String,
    pub optional: bool,
    #[serde(skip)]
    kind: CleanupKind,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum CleanupKind {
    Timer,
    Service,
    Agent,
    Settings,
    Preferences,
    Launcher,
    Icon,
    Updater,
    BsdtarLink,
    Lock,
}

#[derive(Debug, Serialize)]
pub struct CleanupPlan {
    pub items: Vec<CleanupItem>,
    pub preserved_pl: Vec<String>,
    pub preserved_en: Vec<String>,
}

impl CleanupPlan {
    fn add(&mut self, path: &Path, kind: CleanupKind, pl: &str, en: &str, optional: bool) {
        self.items.push(CleanupItem {
            path: path.display().to_string(),
            label_pl: pl.into(),
            label_en: en.into(),
            optional,
            kind,
        });
    }

    fn preserve(&mut self, pl: impl Into<String>, en: impl Into<String>) {
        self.preserved_pl.push(pl.into());
        self.preserved_en.push(en.into());
    }
}

fn plain_file(path: &Path) -> bool {
    fs::symlink_metadata(path).is_ok_and(|metadata| metadata.file_type().is_file())
}

fn manager_unit(path: &Path) -> bool {
    plain_file(path)
        && fs::read_to_string(path).is_ok_and(|content| content.starts_with(MANAGED_UNIT_MARKER))
}

fn manager_launcher(path: &Path) -> bool {
    plain_file(path)
        && fs::read_to_string(path).is_ok_and(|content| {
            content.lines().any(|line| line == DESKTOP_MARKER)
                && content.contains("Name=Plasma Addon Manager")
        })
}

fn data_home(home: &Path) -> Option<PathBuf> {
    let location = std::env::var_os("XDG_DATA_HOME")
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
        .unwrap_or_else(|| home.join(".local/share"));
    // This is a cleanup action. Never remove files at an outside or relative
    // location supplied via XDG_DATA_HOME; users can clean those manually.
    (location.is_absolute() && location.starts_with(home)).then_some(location)
}

fn config_home(home: &Path) -> Option<PathBuf> {
    let location = std::env::var_os("XDG_CONFIG_HOME")
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
        .unwrap_or_else(|| home.join(".config"));
    (location.is_absolute() && location.starts_with(home)).then_some(location)
}

fn make_plan(home: &Path, include_optional: bool) -> CleanupPlan {
    let mut plan = CleanupPlan {
        items: Vec::new(),
        preserved_pl: Vec::new(),
        preserved_en: Vec::new(),
    };
    let units = home.join(".config/systemd/user");
    let timer = units.join(automation::TIMER);
    let service = units.join(automation::SERVICE);

    for (path, kind, pl, en) in [
        (
            &timer,
            CleanupKind::Timer,
            "Harmonogram systemd",
            "Systemd schedule",
        ),
        (
            &service,
            CleanupKind::Service,
            "Usługa systemd",
            "Systemd service",
        ),
    ] {
        if manager_unit(path) {
            plan.add(path, kind, pl, en, false);
        } else if fs::symlink_metadata(path).is_ok() {
            plan.preserve(
                format!("Obca lub zmieniona jednostka systemd: {}", path.display()),
                format!("Unmanaged or modified systemd unit: {}", path.display()),
            );
        }
    }

    let agent = home.join(".local/bin/plasma-addon-manager-agent");
    if plain_file(&agent) {
        plan.add(
            &agent,
            CleanupKind::Agent,
            "Agent aktualizacji",
            "Update agent",
            false,
        );
    }
    let settings = home.join(".config/plasma-addon-manager/settings.toml");
    if plain_file(&settings) {
        plan.add(
            &settings,
            CleanupKind::Settings,
            "Ustawienia automatyzacji",
            "Automation settings",
            false,
        );
    }
    let lock = home.join(".local/state/plasma-addon-manager/update.lock");
    if plain_file(&lock) {
        plan.add(
            &lock,
            CleanupKind::Lock,
            "Blokada aktualizacji",
            "Update lock file",
            false,
        );
    }
    if let Some(config) = config_home(home) {
        let preferences = config.join("wolfgangxxiii/Plasma Addon Manager.conf");
        if plain_file(&preferences) {
            plan.add(
                &preferences,
                CleanupKind::Preferences,
                "Preferencje wyglądu",
                "Appearance preferences",
                false,
            );
        }
    } else {
        plan.preserve(
            "Niestandardowy XDG_CONFIG_HOME poza katalogiem domowym pominięto.",
            "XDG_CONFIG_HOME outside the home directory was skipped.",
        );
    }

    if let Some(data) = data_home(home) {
        let launcher = data.join(format!("applications/{APP_ID}.desktop"));
        if manager_launcher(&launcher) {
            let icon = data.join(format!("icons/hicolor/256x256/apps/{APP_ID}.png"));
            if plain_file(&icon) {
                plan.add(
                    &icon,
                    CleanupKind::Icon,
                    "Ikona AppImage",
                    "AppImage icon",
                    false,
                );
            }
            plan.add(
                &launcher,
                CleanupKind::Launcher,
                "Wpis identyfikacyjny AppImage",
                "AppImage launcher",
                false,
            );
        } else if fs::symlink_metadata(&launcher).is_ok() {
            plan.preserve(
                "Obcy lub zmieniony skrót AppImage pozostanie nietknięty.",
                "An unmanaged or modified AppImage launcher will be preserved.",
            );
        }
    } else {
        plan.preserve(
            "Niestandardowy XDG_DATA_HOME poza katalogiem domowym pominięto.",
            "XDG_DATA_HOME outside the home directory was skipped.",
        );
    }

    let updater = home.join(".local/bin/plasmoid-updater");
    if plain_file(&updater) && valid_updater_version(&updater) {
        if include_optional {
            plan.add(
                &updater,
                CleanupKind::Updater,
                "Lokalny plasmoid-updater",
                "User-local plasmoid-updater",
                true,
            );
        } else {
            plan.preserve(
                "Lokalny plasmoid-updater pozostanie zainstalowany (opcjonalny do usunięcia).",
                "User-local plasmoid-updater will stay installed (optional removal).",
            );
        }
    }
    let bsdtar = home.join(".local/bin/bsdtar");
    if fs::symlink_metadata(&bsdtar).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
        if include_optional {
            plan.add(
                &bsdtar,
                CleanupKind::BsdtarLink,
                "Dowiązanie bsdtar użytkownika",
                "User-local bsdtar symlink",
                true,
            );
        } else {
            plan.preserve(
                "Dowiązanie bsdtar pozostanie (opcjonalne do usunięcia).",
                "The bsdtar symlink will remain (optional removal).",
            );
        }
    }

    // The prior values of this shared file and of migrated legacy timers were
    // not recorded by older releases. Guessing would destroy user changes.
    plan.preserve("Zachowano dodatki KDE, pakiety systemowe (APT/DNF/Zypper/Pacman/Homebrew), kopie migracji i współdzielone ustawienia plasmoid-updater.",
                  "KDE add-ons, system packages (APT/DNF/Zypper/Pacman/Homebrew), migration backups and shared plasmoid-updater settings are preserved.");
    plan.preserve(
        "Sam plik AppImage lub pakiet aplikacji usuń osobno po zamknięciu programu.",
        "Remove the AppImage file or application package separately after closing the app.",
    );
    plan
}

pub fn preview() -> Result<CleanupPlan> {
    Ok(make_plan(&automation::home()?, true))
}

fn systemctl(args: &[&str]) -> Result<()> {
    let output = Command::new("systemctl")
        .arg("--user")
        .args(args)
        .stdin(Stdio::null())
        .output()
        .context("Cannot launch systemctl --user")?;
    if !output.status.success() {
        bail!(
            "systemctl --user {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(())
}

pub fn remove(remove_optional_tools: bool) -> Result<()> {
    let home = automation::home()?;
    let lock = automation::update_lock()?;
    // Re-check all paths immediately before removal: the displayed preview
    // might be outdated if another program modified the files meanwhile.
    let plan = make_plan(&home, remove_optional_tools);
    let has_timer = plan
        .items
        .iter()
        .any(|item| item.kind == CleanupKind::Timer);
    let has_service = plan
        .items
        .iter()
        .any(|item| item.kind == CleanupKind::Service);

    if has_timer {
        systemctl(&["disable", "--now", automation::TIMER])?;
    }
    if has_service {
        systemctl(&["stop", automation::SERVICE])?;
    }
    for item in &plan.items {
        if item.kind == CleanupKind::Lock {
            // Do not unlink the inode while it is locked: that could allow a
            // second updater to take a new lock on the same filename.
            continue;
        }
        let path = Path::new(&item.path);
        fs::remove_file(path).with_context(|| format!("Cannot remove {}", path.display()))?;
        println!("Removed: {}", path.display());
    }
    if has_timer || has_service {
        systemctl(&["daemon-reload"])?;
    }
    // The updating lock belongs to this application. Release the lock before
    // removing its own file, so no subsequent launch sees stale state.
    drop(lock);
    let lock_path = home.join(".local/state/plasma-addon-manager/update.lock");
    if plain_file(&lock_path) {
        fs::remove_file(&lock_path)?;
        if let Some(parent) = lock_path.parent() {
            // Only remove an empty app-specific directory, never recurse.
            let _ = fs::remove_dir(parent);
        }
    }
    // Remove only empty application-specific directories. Migration backups
    // and any other user files keep their parent directory intact.
    for path in [
        home.join(".config/plasma-addon-manager"),
        home.join(".config/wolfgangxxiii"),
    ] {
        let _ = fs::remove_dir(path);
    }
    println!(
        "✓ Removed {} Plasma Addon Manager-owned item(s).",
        plan.items.len()
    );
    println!("Shared packages, KDE add-ons and migration backups were not removed.");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::os::unix::fs::symlink;

    #[test]
    fn preview_only_includes_owned_units_and_launcher() {
        let dir = tempfile::tempdir().unwrap();
        let home = dir.path();
        let units = home.join(".config/systemd/user");
        fs::create_dir_all(&units).unwrap();
        fs::write(
            units.join(automation::TIMER),
            format!("{MANAGED_UNIT_MARKER}\n[Timer]\n"),
        )
        .unwrap();
        fs::write(
            units.join(automation::SERVICE),
            "[Service]\nExecStart=/tmp/foreign\n",
        )
        .unwrap();
        let app_dir = home.join(".local/share/applications");
        fs::create_dir_all(&app_dir).unwrap();
        fs::write(
            app_dir.join(format!("{APP_ID}.desktop")),
            format!("[Desktop Entry]\nName=Plasma Addon Manager\n{DESKTOP_MARKER}\n"),
        )
        .unwrap();
        let plan = make_plan(home, false);
        assert!(plan
            .items
            .iter()
            .any(|item| item.kind == CleanupKind::Timer));
        assert!(plan
            .items
            .iter()
            .any(|item| item.kind == CleanupKind::Launcher));
        assert!(!plan
            .items
            .iter()
            .any(|item| item.kind == CleanupKind::Service));
    }

    #[test]
    fn optional_tools_require_explicit_choice() {
        let dir = tempfile::tempdir().unwrap();
        let home = dir.path();
        let bin = home.join(".local/bin");
        fs::create_dir_all(&bin).unwrap();
        let target = home.join("other/bsdtar");
        fs::create_dir_all(target.parent().unwrap()).unwrap();
        fs::write(&target, b"tool").unwrap();
        symlink(&target, bin.join("bsdtar")).unwrap();
        assert!(!make_plan(home, false)
            .items
            .iter()
            .any(|item| item.kind == CleanupKind::BsdtarLink));
        assert!(make_plan(home, true)
            .items
            .iter()
            .any(|item| item.kind == CleanupKind::BsdtarLink));
    }

    #[test]
    fn does_not_follow_symlinked_settings_or_units() {
        let dir = tempfile::tempdir().unwrap();
        let home = dir.path();
        let source = home.join("foreign-file");
        fs::write(&source, format!("{MANAGED_UNIT_MARKER}\n")).unwrap();
        let units = home.join(".config/systemd/user");
        fs::create_dir_all(&units).unwrap();
        symlink(&source, units.join(automation::TIMER)).unwrap();
        let settings = home.join(".config/plasma-addon-manager/settings.toml");
        fs::create_dir_all(settings.parent().unwrap()).unwrap();
        symlink(&source, &settings).unwrap();
        let plan = make_plan(home, false);
        assert!(!plan
            .items
            .iter()
            .any(|item| item.kind == CleanupKind::Timer || item.kind == CleanupKind::Settings));
    }
}
